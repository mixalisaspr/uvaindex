// A supported language code from anything lang-like ('de', 'zh-Hans',
// 'fr-CA', null); unknown values give English.
export function normalizeLang(value) {
  const code = String(value || '').toLowerCase().split(/[-_]/)[0];
  return LANGS.includes(code) ? code : DEFAULT_LANG;
}

// Language of the current page (<html lang>), or English outside a browser.
export function pageLang() {
  return normalizeLang(typeof document !== 'undefined' ? document.documentElement.lang : null);
}

export function localeFor(lang) {
  return LOCALES[normalizeLang(lang)];
}

// Path prefix of a language's pages relative to the site root: '' for
// English, 'de/' for German...
export function langPath(lang) {
  const code = normalizeLang(lang);
  return code === DEFAULT_LANG ? '' : `${code}/`;
}

// Translator for one language: t('refresh'), t('rows.zenith'),
// t('summaryPeak', { day, index }). Falls back to English, then to the key.
export function translator(lang) {
  const code = normalizeLang(lang);
  const lookup = (table, key) =>
    key.split('.').reduce((v, k) => (v && typeof v === 'object' ? v[k] : undefined), table);
  return (key, vars) => {
    let s = lookup(STRINGS[code], key);
    if (s === undefined) s = lookup(STRINGS.en, key);
    if (s === undefined) return key;
    if (typeof s !== 'string' || !vars) return s;
    return s.replace(/\{(\w+)\}/g, (m, k) => (k in vars ? String(vars[k]) : m));
  };
}

// Display name of a UVA band (by its level 0-4) in a language.
export function bandLabel(level, lang) {
  return translator(lang)('bands')[level] ?? '';
}

// Every key present in English, for tests: each language must define them all.
export function stringKeys(lang) {
  const out = [];
  const walk = (obj, prefix) => {
    for (const [k, v] of Object.entries(obj)) {
      const key = prefix ? `${prefix}.${k}` : k;
      if (v && typeof v === 'object' && !Array.isArray(v)) walk(v, key);
      else out.push(key);
    }
  };
  walk(STRINGS[normalizeLang(lang)] || {}, '');
  return out;
}
